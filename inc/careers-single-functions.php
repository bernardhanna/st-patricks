function matrix_prepare_careers_application_form(int $post_id, array $args = []): array
{
    $defaults = matrix_get_careers_application_form_defaults();
    $job_title = get_the_title($post_id);
    $privacy_url = home_url('/about-us/policies-and-publications/data-protection/');

    $recipient = trim((string) ($args['recipient_email'] ?? ''));
    if ($recipient === '' && function_exists('get_field')) {
        $recipient = trim((string) get_field('career_application_email', $post_id));
    }
    if ($recipient === '') {
        $recipient = (string) $defaults['recipient_email'];
    }

    return [
        'post_id' => $post_id,
        'job_title' => $job_title,
        'form_id' => 'careers-application-' . $post_id,
        'section_id' => 'careers-application-' . $post_id,
        'submit_label' => trim((string) ($args['submit_label'] ?? '')) ?: (string) $defaults['submit_label'],
        'success_message' => trim((string) ($args['success_message'] ?? '')) ?: (string) $defaults['success_message'],
        'form_name' => trim((string) ($args['form_name'] ?? '')) ?: (string) $defaults['form_name'],
        'subject' => trim((string) ($args['subject'] ?? '')) ?: ($defaults['subject_prefix'] . ' – ' . $job_title),
        'recipient_email' => $recipient,
        'privacy_policy_url' => $privacy_url,
        'privacy_policy_label' => (string) $defaults['privacy_policy_label'],
        'terms_text' => (string) $defaults['terms_text'],
        'submission_uid' => function_exists('wp_generate_uuid4') ? wp_generate_uuid4() : uniqid('careers-', true),
        'title_options' => matrix_get_careers_application_title_options(),
        'country_options' => matrix_get_careers_application_country_options(),
        'county_options' => matrix_get_careers_application_county_options(),
        'source_options' => matrix_get_careers_application_source_options(),
        'eligibility_options' => matrix_get_careers_application_eligibility_options(),
        'yes_no_options' => matrix_get_careers_application_yes_no_options(),
    ];
}

function matrix_get_career_job_description_html(int $post_id): string
{
    if (function_exists('get_field')) {
        $acf_content = trim((string) get_field('career_job_description', $post_id));
        if ($acf_content !== '') {
            return $acf_content;
        }
    }

    $content = get_post_field('post_content', $post_id);

    return is_string($content) ? $content : '';
}

function matrix_career_shows_application_form(int $post_id): bool
{
    if (function_exists('get_field')) {
        return (bool) get_field('career_show_application_form', $post_id);
    }

    return false;
}

function matrix_get_careers_single_back_url(): string
{
    $archive = function_exists('get_post_type_archive_link') ? get_post_type_archive_link('careers') : '';

    return is_string($archive) && $archive !== '' ? $archive : home_url('/careers/');
}

/**
 * Resolve the first taxonomy term name assigned to a careers post.
 */
function matrix_get_career_first_term_name(int $post_id, string $taxonomy): string
{
    $terms = function_exists('get_the_terms') ? get_the_terms($post_id, $taxonomy) : false;

    if (is_array($terms)) {
        foreach ($terms as $term) {
            if ($term instanceof WP_Term) {
                return $term->name;
            }
        }
    }

    return '';
}

/**
 * Ordered key/value meta rows shown in the careers single hero.
 *
 * @return array<int, array{label: string, value: string}>
 */
function matrix_get_career_hero_meta(int $post_id): array
{
    $area = function_exists('get_field') ? trim((string) get_field('career_area', $post_id)) : '';
    $location = matrix_get_career_first_term_name($post_id, 'career_location');
    $job_type = function_exists('get_field') ? trim((string) get_field('career_job_type', $post_id)) : '';
    $category = function_exists('get_field') ? trim((string) get_field('career_category', $post_id)) : '';

    if ($category === '') {
        $category = matrix_get_career_first_term_name($post_id, 'career_department');
    }

    $rows = [
        ['label' => 'Area', 'value' => $area],
        ['label' => 'Location', 'value' => $location],
        ['label' => 'Job Type', 'value' => $job_type],
        ['label' => 'Category', 'value' => $category],
    ];

    return array_values(array_filter($rows, static fn (array $row): bool => $row['value'] !== ''));
}

/**
 * Share links for a careers vacancy. Mirrors the blog single share links.
 *
 * @return array<int, array<string, mixed>>
 */
