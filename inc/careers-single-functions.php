{
    $post_id = (int) ($post_id ?: (function_exists('get_the_ID') ? (int) get_the_ID() : 0));

    if (function_exists('matrix_get_blog_post_share_links')) {
        return matrix_get_blog_post_share_links($post_id);
    }

    return [];
}
